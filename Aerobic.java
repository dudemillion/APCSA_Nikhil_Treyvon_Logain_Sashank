public class Aerobic {
    double Stamina;
    double JumpPower;
    public Aerobic(double Stamina, double JumpPower) {
		this.Stamina = Stamina;
		this.JumpPower=JumpPower;
	}
	public double GetStamina() {
	    return this.Stamina;
	}
	public double GetJump(){
	    return this.JumpPower;
	}
}
